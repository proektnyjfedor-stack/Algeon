def dart_concat_string(s: str) -> str:
    parts = []
    for line in s.split("\n"):
        escaped = line.replace("\\", "\\\\").replace("'", "\\'")
        parts.append(f"'{escaped}\\n'")
    return "\n      ".join(parts) if parts else "''"


